export const TOWER_LIST = Object.values(TOWER_DEFS);

export function getTowerDef(id: string): TowerDef {
  return TOWER_DEFS[id];
}

export function getTowerUpgradeCost(def: TowerDef, currentLevel: number): number {
  return Math.round(def.cost * Math.pow(def.upgradeCostMultiplier, currentLevel + 1));
}

export function getTowerSellValue(def: TowerDef, level: number): number {
  let total = def.cost;
  for (let i = 0; i < level; i++) {
    total += Math.round(def.cost * Math.pow(def.upgradeCostMultiplier, i + 1));
  }
  return Math.round(total * 0.6);
}

export function getTowerDamageAtLevel(def: TowerDef, level: number): number {
  return Math.round(def.damage * Math.pow(def.upgradeDamageMultiplier, level));
}
